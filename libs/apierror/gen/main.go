// Command gen 从 proto/errors.json 生成双语言错误码常量（spec-0.8 D1）。
// 纯 stdlib，无第三方依赖；生成物按 development-standards §0 豁免 lint/覆盖率。
// 生成期校验（spec-0.8 T4）：message 模板禁含占位符（%、{}），动态内容走 details。
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

type registry struct {
	Domains []string `json:"domains"`
	Codes   []entry  `json:"codes"`
}

type entry struct {
	Code        string `json:"code"`
	Level       string `json:"level"`
	HTTP        int    `json:"http"`
	Message     string `json:"message"`
	Description string `json:"description"`
	Deprecated  bool   `json:"deprecated"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen-errors:", err)
		os.Exit(1)
	}
}

func run() error {
	root, err := repoRoot()
	if err != nil {
		return err
	}
	// 路径由 repoRoot 锚定到仓库内固定文件，属构建工具信任边界，非用户输入。
	raw, err := os.ReadFile(filepath.Join(root, "proto", "errors.json")) //nolint:gosec // G304 见上行说明
	if err != nil {
		return fmt.Errorf("read registry: %w", err)
	}
	var reg registry
	if err := json.Unmarshal(raw, &reg); err != nil {
		return fmt.Errorf("parse registry: %w", err)
	}
	if err := validate(reg); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(root, "libs", "apierror", "codes_gen.go"),
		[]byte(genGo(reg)), 0o600); err != nil {
		return fmt.Errorf("write go codes: %w", err)
	}
	if err := os.WriteFile(filepath.Join(root, "skills", "airush_skills", "error_codes_gen.py"),
		[]byte(genPy(reg)), 0o600); err != nil {
		return fmt.Errorf("write python codes: %w", err)
	}
	fmt.Printf("gen-errors: %d codes generated\n", len(reg.Codes))
	return nil
}

// repoRoot 从当前目录向上找 go.work。
func repoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.work")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.work not found（须在仓库内执行）")
		}
		dir = parent
	}
}

func validate(reg registry) error {
	validLevel := map[string]bool{"E1": true, "E2": true, "E3": true, "E4": true, "E5": true, "E6": true}
	domains := map[string]bool{}
	for _, d := range reg.Domains {
		domains[d] = true
	}
	seen := map[string]bool{}
	for _, c := range reg.Codes {
		if seen[c.Code] {
			return fmt.Errorf("%s: 码重复", c.Code)
		}
		seen[c.Code] = true
		parts := strings.SplitN(c.Code, "_", 3)
		if len(parts) != 3 || parts[0] != "AR" {
			return fmt.Errorf("%s: 码格式必须 AR_<DOMAIN>_<REASON>", c.Code)
		}
		if !domains[parts[1]] {
			return fmt.Errorf("%s: 域 %s 未在 domains 注册", c.Code, parts[1])
		}
		if !validLevel[c.Level] {
			return fmt.Errorf("%s: 非法 level %q", c.Code, c.Level)
		}
		if c.HTTP < 400 || c.HTTP > 599 {
			return fmt.Errorf("%s: http 状态 %d 越界", c.Code, c.HTTP)
		}
		if c.Message == "" {
			return fmt.Errorf("%s: message 不能为空", c.Code)
		}
		if strings.ContainsAny(c.Message, "%{}") {
			return fmt.Errorf("%s: message 模板禁含占位符（动态内容走 details，spec-0.8 §2.2）", c.Code)
		}
	}
	return nil
}

func genGo(reg registry) string {
	var b strings.Builder
	b.WriteString("// Code generated by libs/apierror/gen from proto/errors.json. DO NOT EDIT.\n\n")
	b.WriteString("package apierror\n\n")
	b.WriteString("// 全部注册错误码（spec-0.8）。\nconst (\n")
	for _, c := range reg.Codes {
		fmt.Fprintf(&b, "\t%s Code = %q\n", constName(c.Code), c.Code)
	}
	b.WriteString(")\n\nvar codeMeta = map[Code]Meta{\n")
	for _, c := range reg.Codes {
		fmt.Fprintf(&b, "\t%s: {Level: %q, HTTP: %d, Message: %q, Deprecated: %v},\n",
			constName(c.Code), c.Level, c.HTTP, c.Message, c.Deprecated)
	}
	b.WriteString("}\n")
	return b.String()
}

// constName AR_TENANT_NOT_FOUND → CodeTenantNotFound。
func constName(code string) string {
	parts := strings.Split(strings.TrimPrefix(code, "AR_"), "_")
	var b strings.Builder
	b.WriteString("Code")
	for _, p := range parts {
		b.WriteString(strings.ToUpper(p[:1]) + strings.ToLower(p[1:]))
	}
	return b.String()
}

func genPy(reg registry) string {
	var b strings.Builder
	b.WriteString("\"\"\"Generated by libs/apierror/gen from proto/errors.json. DO NOT EDIT.\"\"\"\n\n")
	b.WriteString("ERROR_CODES: dict[str, dict[str, object]] = {\n")
	for _, c := range reg.Codes {
		fmt.Fprintf(&b, "    %q: {\"level\": %q, \"http\": %d, \"message\": %q, \"deprecated\": %v},\n",
			c.Code, c.Level, c.HTTP, c.Message, pyBool(c.Deprecated))
	}
	b.WriteString("}\n")
	return b.String()
}

func pyBool(v bool) string {
	if v {
		return "True"
	}
	return "False"
}
